import * as Effect from "effect/Effect"
import * as FileSystem from "effect/FileSystem"
import * as Option from "effect/Option"
import * as Path from "effect/Path"
import * as Schema from "effect/Schema"
import * as Migrator from "effect/sql/Migrator"
import { SqlClient } from "effect/sql/SqlClient"
import type { SqlError } from "effect/sql/SqlError"

const snapshotRows = Schema.Array(
  Schema.Struct({
    sql: Schema.String,
    table_kind: Schema.Literals(["table", "view", "virtual", "shadow"]),
  }),
)

/** Snapshot failures retain the output path; migration commits precede snapshot replacement. */
export class SchemaSnapshotError extends Schema.TaggedError<
  SchemaSnapshotError,
  { readonly brand: unique symbol }
>()("SchemaSnapshotError", {
  source: Schema.String,
  detail: Schema.String,
  cause: Schema.optionalKey(Schema.Defect()),
}) {
  /** A stable message identifies the schema snapshot that needs regeneration. */
  override get message(): string {
    return `Silt schema snapshot failed: ${this.detail} (${this.source})`
  }
}

/** Migration effects run against the supplied client; snapshot paths are relative to the working directory. */
export interface MigrationsWithSnapshotOptions<R = never> {
  readonly loader: Migrator.Loader<R>
  readonly snapshotPath: string
  /** Use the same migration history table as the application's regular migrator. */
  readonly table?: string
}

/**
 * Apply Effect SQL migrations and atomically export SQLite DDL for existing .sql imports.
 * A no-op migration run also refreshes the snapshot. Export failures remain typed after migrations commit.
 * Use a fresh development database to derive the snapshot from the migration history alone.
 * Call outside an existing transaction so the exported schema reflects committed migrations.
 */
export const runMigrationsWithSnapshot = Effect.fn("Silt.runMigrationsWithSnapshot")(function* <R>(
  options: MigrationsWithSnapshotOptions<R>,
): Effect.fn.Return<
  ReadonlyArray<readonly [id: number, name: string]>,
  Migrator.MigrationError | SqlError | SchemaSnapshotError,
  SqlClient | FileSystem.FileSystem | Path.Path | R
> {
  const sql = yield* SqlClient
  const fs = yield* FileSystem.FileSystem
  const path = yield* Path.Path
  const destination = path.resolve(options.snapshotPath)
  if (!sql.onDialectOrElse({ sqlite: () => true, orElse: () => false }))
    return yield* new SchemaSnapshotError({
      source: destination,
      detail: "Only SQLite schema snapshots are supported",
    })
  const transaction = yield* Effect.serviceOption(sql.transactionService)
  if (Option.isSome(transaction))
    return yield* new SchemaSnapshotError({
      source: destination,
      detail: "Run migration snapshots outside an existing transaction",
    })

  const table = options.table ?? "effect_sql_migrations"
  const completed = yield* Migrator.make({})({ loader: options.loader, table }).pipe(
    // Effect's migrator reports failed migration effects as MigrationError defects.
    // Preserve unrelated defects while returning known migration failures in the typed channel.
    Effect.catchDefect((cause) =>
      cause instanceof Migrator.MigrationError ? Effect.fail(cause) : Effect.die(cause),
    ),
  )
  const rows = yield* sql.unsafe<Record<string, unknown>>(
    `
    SELECT s.sql, p.type AS table_kind
    FROM main.sqlite_schema s
    JOIN pragma_table_list p ON p.schema = 'main' AND p.name = s.tbl_name
    WHERE s.sql IS NOT NULL
      AND s.name NOT GLOB 'sqlite_*'
      AND s.tbl_name <> ? COLLATE NOCASE
    ORDER BY CASE s.type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'view' THEN 2 ELSE 3 END, s.name
  `,
    [table],
  ).withoutTransform
  const objects = yield* Schema.decodeUnknownEffect(snapshotRows)(rows).pipe(
    Effect.mapError(
      (cause) =>
        new SchemaSnapshotError({
          source: destination,
          detail: "Cannot decode SQLite schema metadata",
          cause,
        }),
    ),
  )
  if (objects.some((object) => object.table_kind === "virtual" || object.table_kind === "shadow"))
    return yield* new SchemaSnapshotError({
      source: destination,
      detail: "Virtual tables and their shadow tables cannot be exported",
    })

  const schema =
    "-- Generated by effect-silt from applied migrations. Do not edit.\n\n" +
    objects.map((object) => object.sql.trimEnd().replace(/;$/, "") + ";\n").join("\n")
  yield* Effect.gen(function* () {
    const directory = path.dirname(destination)
    yield* fs.makeDirectory(directory, { recursive: true })
    const temporary = yield* fs.makeTempDirectoryScoped({ directory, prefix: ".silt-snapshot-" })
    const candidate = path.join(temporary, "schema.sql")
    yield* fs.writeFileString(candidate, schema)
    yield* fs.rename(candidate, destination)
  }).pipe(
    Effect.scoped,
    Effect.mapError(
      (cause) =>
        new SchemaSnapshotError({
          source: destination,
          detail: "Cannot write schema snapshot",
          cause,
        }),
    ),
  )
  return completed
})
